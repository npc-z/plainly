#!/usr/bin/env bash
#
# Generates the CLI's synthetic workspace, `nix/cli-workspace/Cargo.toml` and
# `nix/cli-workspace/Cargo.lock`, from the real workspace's root `Cargo.toml`
# and `Cargo.lock`.
#
# The CLI package (`.#plainly`) is built from a workspace of just two crates.
# That is not tidiness: a workspace containing the GUI crates resolves
# `libdbus-sys`, whose build script panics in a build sandbox.
#
# The manifest is a projection of the root one. What the projection is lives in
# `scripts/cli_workspace.py`, shared with `scripts/check-cli-workspace.sh`, so
# the rule has one owner.
#
# The lock cannot be projected by pruning alone. `Cargo.lock` does not record
# which features were enabled, so the root lock over-approximates the CLI's
# optional edges (the GUI activates them), and `cargo --locked`, which crane
# always passes, rejects the over-approximation. So cargo normalises it: the
# script seeds cargo with the pruned root lock, which pins the versions to the
# root workspace's choices, and lets `cargo metadata` write the exact lock.
# Nothing is upgraded. The seed's versions are kept and cargo drops only what
# the CLI does not need.
#
# Usage:
#   scripts/generate-cli-workspace.sh           # write nix/cli-workspace/
#   scripts/generate-cli-workspace.sh --check   # compare, write nothing
#
# Run it inside `nix develop`: it needs that shell's cargo (the same resolver
# the build uses) and python3. The first run needs network or a populated cargo
# cache, because cargo reads the manifest of every dependency to normalise the
# lock. After that it is instant.
set -euo pipefail

cd "$(dirname "$0")/.."

usage() {
    echo "usage: $0 [--check]" >&2
    exit 2
}

fail() {
    echo "FAIL: $*" >&2
    exit 1
}

check=false
case "${1:-}" in
    "") ;;
    --check) check=true ;;
    *) usage ;;
esac

command -v cargo >/dev/null || fail "cargo is not on PATH — run this inside \`nix develop\`"
command -v python3 >/dev/null || fail "python3 is not on PATH — run this inside \`nix develop\`"
python3 -c 'import tomllib' 2>/dev/null || fail "python3 has no tomllib (needs 3.11+)"

# The lock must be written by the same cargo the build uses, because a host
# cargo is a different resolver and would normalise the seed differently. The
# expected version is read from flake.nix rather than repeated here: the sed
# pattern mirrors the `channel = "...";` line there, so a toolchain refactor
# updates both.
channel=$(sed -n 's/^[[:space:]]*channel = "\([^"]*\)";.*$/\1/p' flake.nix | head -n 1)
[ -n "$channel" ] || fail "cannot read the Rust toolchain channel from flake.nix"
cargo_version=$(cargo --version 2>/dev/null || true)
case "$cargo_version" in
    "cargo ${channel} "*) ;;
    *) fail "cargo is not the dev shell's ${channel} (got: ${cargo_version:-none}) — run this inside \`nix develop\`" ;;
esac

work=$(mktemp -d)
keep_work=false
trap 'if ! $keep_work; then rm -rf "$work"; fi' EXIT

if python3 - "$check" "$work" <<'PYEOF'
import os
import shutil
import subprocess
import sys

# Importing the shared projection must not leave `scripts/__pycache__/` behind
# in a checkout this script only reads.
sys.dont_write_bytecode = True

# The projection rule is shared with the guard; `scripts/` is on the path
# because both scripts start from the repository root.
sys.path.insert(0, os.path.join(os.getcwd(), "scripts"))
import cli_workspace

check = sys.argv[1] == "true"
work = sys.argv[2]
out_dir = "nix/cli-workspace"
manifest_path = os.path.join(out_dir, "Cargo.toml")
lock_path = os.path.join(out_dir, "Cargo.lock")


def die(message):
    print(f"FAIL: {message}", file=sys.stderr)
    sys.exit(1)


try:
    generated_manifest = cli_workspace.render_manifest(cli_workspace.manifest_projection())
except KeyError as error:
    die(error.args[0])

try:
    kept = cli_workspace.root_lock_closure(cli_workspace.load("Cargo.lock")["package"])
except KeyError as error:
    die(error.args[0])

seed_lines = [
    "# This file is automatically @generated by Cargo.",
    "# It is not intended for manual editing.",
    "version = 4",
    "",
]
for package in kept:
    seed_lines.append("[[package]]")
    seed_lines.append(f"name = {cli_workspace.quote(package['name'])}")
    seed_lines.append(f"version = {cli_workspace.quote(package['version'])}")
    for key in ("source", "checksum"):
        if key in package:
            seed_lines.append(f"{key} = {cli_workspace.quote(package[key])}")
    if package.get("dependencies"):
        seed_lines.append("dependencies = [")
        seed_lines += [f" {cli_workspace.quote(dependency)}," for dependency in package["dependencies"]]
        seed_lines.append("]")
    seed_lines.append("")
generated_seed = "\n".join(seed_lines)

os.makedirs(os.path.join(work, "crates"), exist_ok=True)
for member in cli_workspace.MEMBERS:
    shutil.copytree(member, os.path.join(work, member))
with open(os.path.join(work, "Cargo.toml"), "w") as handle:
    handle.write(generated_manifest)
with open(os.path.join(work, "Cargo.lock"), "w") as handle:
    handle.write(generated_seed)
work_lock = os.path.join(work, "Cargo.lock")

# Offline first: a machine that has built the workspace already has the crates
# cached. The online retry is only for a genuine cache miss, and any other
# failure (a manifest this cargo cannot read, a malformed seed) is reported as
# itself rather than blamed on the cache.
CACHE_MISS_MARKERS = (
    "offline",
    "no matching package",
    "can't find crate",
    "failed to download",
    "unable to get packages from source",
)


def run_metadata(offline):
    command = ["cargo", "metadata", "--format-version", "1"]
    if offline:
        command.insert(2, "--offline")
    return subprocess.run(command, cwd=work, capture_output=True, text=True)


metadata = run_metadata(offline=True)
if metadata.returncode != 0:
    if not any(marker in metadata.stderr.lower() for marker in CACHE_MISS_MARKERS):
        print(metadata.stderr, file=sys.stderr)
        die("cargo metadata failed before it could normalise the seeded lock")
    print(
        "   cargo cache is incomplete; re-running cargo metadata with network access",
        file=sys.stderr,
    )
    metadata = run_metadata(offline=False)
if metadata.returncode != 0:
    print(metadata.stderr, file=sys.stderr)
    die("cargo could not normalise the seeded lock")

with open(work_lock) as handle:
    generated_lock = handle.read()

normalised = cli_workspace.load(work_lock)
print(f"   {len(normalised['package'])} packages in the normalised lock (seed: {len(kept)})")

if check:
    stale = []
    for path, generated in ((manifest_path, generated_manifest), (lock_path, generated_lock)):
        try:
            with open(path) as handle:
                committed = handle.read()
        except FileNotFoundError:
            die(f"{path} does not exist — run without --check to generate it")
        if committed != generated:
            stale.append(path)
    if stale:
        for path in stale:
            print(f"FAIL: {path} is stale — run scripts/generate-cli-workspace.sh", file=sys.stderr)
        sys.exit(1)
    print("ok: nix/cli-workspace/ is up to date")
    sys.exit(0)

os.makedirs(out_dir, exist_ok=True)
with open(manifest_path, "w") as handle:
    handle.write(generated_manifest)
with open(lock_path, "w") as handle:
    handle.write(generated_lock)
print(f"wrote {manifest_path} and {lock_path}")
PYEOF
then
    :
else
    keep_work=true
    if $check; then
        fail "the check failed (see above); the working copy is at $work"
    fi
    fail "the generator failed; its working copy is at $work"
fi

if ! $check; then
    git --no-pager diff --stat -- nix/cli-workspace 2>/dev/null || true
fi
