"""The CLI workspace's projection rule.

`flake.nix` builds the command line from a workspace of two crates, and that
workspace's manifest is a projection of the root one. Both the generator
(`scripts/generate-cli-workspace.sh`) and its guard
(`scripts/check-cli-workspace.sh`) have to agree on what that projection is;
this module is the agreement, so a change to the rule is one edit rather than
two that can drift apart.

It is deliberately plain: no cargo, no Nix, no side effects — importing it from
either script is safe, including from the guard that must stay offline.
"""

import os
import tomllib

# The two crates the CLI package is built from. `flake.nix`'s `cliSource` copies
# the same two directories; adding a crate edits both places (one is a Nix path
# expression, the other this list).
MEMBERS = ["crates/plainly-core", "crates/plainly-cli"]

DEPENDENCY_SECTIONS = ("dependencies", "dev-dependencies", "build-dependencies")

# The `[workspace]` keys the projection knows how to carry. A new one is not a
# silently-dropped setting: `manifest_projection` refuses it until this module
# (and the guard that checks the projection) learns what to do with it.
KNOWN_WORKSPACE_KEYS = {"resolver", "members", "package", "dependencies"}


def load(path):
    with open(path, "rb") as handle:
        return tomllib.load(handle)


def member_name(member):
    """`crates/plainly-core` -> `plainly-core` (the name Cargo.lock uses)."""
    return member.rsplit("/", 1)[-1]


def inherited_dependency_names(root="."):
    """The workspace.dependencies names the member crates inherit, deduplicated."""
    names = []
    seen = set()
    for member in MEMBERS:
        crate = load(os.path.join(root, member, "Cargo.toml"))
        for section in DEPENDENCY_SECTIONS:
            for name, spec in crate.get(section, {}).items():
                if isinstance(spec, dict) and spec.get("workspace") is True and name not in seen:
                    seen.add(name)
                    names.append(name)
    return names


def manifest_projection(root="."):
    """The manifest the CLI workspace should have, as parsed TOML."""
    workspace = load(os.path.join(root, "Cargo.toml"))["workspace"]
    unknown = sorted(set(workspace) - KNOWN_WORKSPACE_KEYS)
    if unknown:
        raise KeyError(
            "the root Cargo.toml has [workspace] settings the CLI projection does not carry: "
            + ", ".join(f"[workspace.{key}]" for key in unknown)
            + " — update scripts/cli_workspace.py and its guard"
        )
    declared = workspace["dependencies"]
    names = inherited_dependency_names(root)
    missing = [name for name in names if name not in declared]
    if missing:
        raise KeyError(
            "the root Cargo.toml has no [workspace.dependencies] for: " + ", ".join(missing)
        )
    inherited = set(names)
    return {
        "workspace": {
            "resolver": workspace["resolver"],
            "members": list(MEMBERS),
            "package": workspace["package"],
            # Only the inherited entries, in the root manifest's order. A dep the
            # GUI alone uses must not appear: the projection is the CLI's view.
            "dependencies": {
                name: declared[name] for name in declared if name in inherited
            },
        }
    }


def quote(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_value(value):
    if isinstance(value, str):
        return quote(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return "[" + ", ".join(render_value(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(
            f"{key} = {render_value(item)}" for key, item in value.items()
        ) + " }"
    raise TypeError(f"unexpected TOML value: {value!r}")


def render_manifest(manifest):
    """The committed text of `nix/cli-workspace/Cargo.toml`."""
    workspace = manifest["workspace"]
    lines = [
        "# Generated by scripts/generate-cli-workspace.sh from the root workspace's manifests.",
        "# Do not edit by hand; run the generator instead.",
        "",
        "[workspace]",
        f"resolver = {quote(workspace['resolver'])}",
        "members = [",
    ]
    lines += [f"  {quote(member)}," for member in workspace["members"]]
    lines += ["]", "", "[workspace.package]"]
    for key, value in workspace["package"].items():
        lines.append(f"{key} = {render_value(value)}")
    lines += ["", "[workspace.dependencies]"]
    for name, value in workspace["dependencies"].items():
        lines.append(f"{name} = {render_value(value)}")
    return "\n".join(lines) + "\n"


def dependency_name_version(entry):
    """`"name"` or `"name version"` — the lock's two dependency-entry forms."""
    name, _, version = entry.partition(" ")
    return name, version or None


def root_lock_closure(packages):
    """The root lock's packages reachable from the CLI's two crates.

    A superset of the CLI's own resolution: the root lock was resolved with the
    GUI's features, so it records optional edges the CLI never activates. Cargo
    prunes those when it normalises this closure into `nix/cli-workspace/`.
    """
    by_name = {}
    for package in packages:
        by_name.setdefault(package["name"], []).append(package)

    def resolve(entry):
        name, version = dependency_name_version(entry)
        candidates = by_name.get(name)
        if not candidates:
            raise KeyError(f"Cargo.lock has no package for dependency {entry!r}")
        if version is not None:
            for candidate in candidates:
                if candidate["version"] == version:
                    return candidate
            raise KeyError(f"Cargo.lock has no {name} {version} (dependency {entry!r})")
        return candidates[0]

    seen = set()
    stack = []
    for member in MEMBERS:
        name = member_name(member)
        if name not in by_name:
            raise KeyError(f"Cargo.lock has no workspace member {name!r}")
        stack += [package for package in by_name[name] if "source" not in package]
    if not stack:
        raise KeyError("Cargo.lock has no workspace-rooted packages for the CLI workspace")
    while stack:
        package = stack.pop()
        key = (package["name"], package["version"])
        if key in seen:
            continue
        seen.add(key)
        for dependency in package.get("dependencies", []):
            target = resolve(dependency)
            if "source" in target:
                stack.append(target)
    kept = [package for package in packages if (package["name"], package["version"]) in seen]
    if not kept:
        raise KeyError("the CLI closure in Cargo.lock is empty")
    return kept
